    // Admin-Oberfläche steht data-i18n in dashboard.html immer auf einem reinen Text-Element
    // (<span>/<strong>), nie auf dem Icon-Elternelement -- el.textContent überschreibt daher
    // nirgends ein Icon, und es sind keine manuellen Patches nötig. Bleibt als Platzhalter für
    // künftige Fälle, bei denen das nicht mehr gilt.
    applyUserDOM: () => {
        if (!q('#btn-create-ticket') && !q('#user-tickets')) return;
    }
